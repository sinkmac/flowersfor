		<h1>Flowers and the Groom's Side: What You're Responsible For</h1>

		<p class="lede">Weddings run on flowers, and a specific slice of them lands on the groom's side of the ledger. If you're the groom or the best man and someone has said the word "buttonholes" at you, this is the full picture in five minutes.</p>

		<h2>What the groom's side traditionally covers</h2>
		<p>Tradition (loosely observed these days, but a useful default) puts these with the groom:</p>
		<p><strong>Buttonholes</strong> for the groom, best man, ushers, and both fathers</p>
		<p><strong>The bride's bouquet</strong> — yes, traditionally the groom's purchase, a detail that surprises most grooms</p>
		<p><strong>Corsages for the two mums</strong> (and grandmothers, if attending)</p>
		<p><strong>Thank-you bouquets</strong> presented during the speeches</p>
		<p>In practice, most couples now fold all flowers into one wedding-florist order. But if you're doing any of it separately — or the planning has split along traditional lines — the list above is yours.</p>

		<h2>Buttonholes: the two rules</h2>
		<p><strong>Match the bridal flowers.</strong> A buttonhole is an echo of the bouquet, not a solo act. One rose or one sprig that ties to the main arrangements. Your florist will know; your job is just to confirm the count.</p>
		<p><strong>Count everyone, then add two.</strong> Groom, best man, ushers, both dads — then a couple of spares, because someone's buttonhole will end up crushed in a hug or lost in a car before the ceremony. Spares cost pennies; a dad without a buttonhole in the photos costs more.</p>

		<h2>The thank-you bouquets</h2>
		<p>These appear during the best man's or groom's speech — typically for both mums, and anyone who did heroic unpaid work (the aunt who made the cake). Two to four modest bouquets, handed over at the "we'd like to thank" moment. <strong>This is the one most commonly forgotten</strong>, because it belongs to nobody until the week of the wedding. Best man: this is yours to remember. Put it in your speech notes now.</p>

		<h2>Timing</h2>
		<p>Buttonholes and corsages are made fresh the day before or the morning of. Confirm the order two weeks out; confirm collection or delivery three days out. Thank-you bouquets can arrive the morning of the wedding and sit in water somewhere cool until the speeches.</p>

		<h2>If you've been sent here mid-panic</h2>
		<p>Wedding this week and none of it's ordered? A good florist can turn buttonholes around in 48 hours. Ring rather than order online — say the date, the count, and the bouquet colours if you know them. Then order the thank-you bouquets below and you're covered.</p>

