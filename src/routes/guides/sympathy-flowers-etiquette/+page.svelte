		<h1>Sympathy Flowers: A Plain Guide</h1>

\t\t<p class="lede">If you are reading this, someone has died, and you want to do the right thing by the people left behind. This page tells you what to send, when, and what to write. It is short on purpose.</p>

\t\t<h2>Whether to send flowers at all</h2>
\t\t<p>Check the funeral notice first. Some families ask for donations to a charity instead of flowers. If they do, honour that — send a card, and make the donation. If nothing is specified, flowers are appropriate and will not be wrong.</p>

\t\t<h2>Two different things people mean by "sympathy flowers"</h2>
\t\t<p><strong>Flowers for the funeral itself.</strong> These go to the funeral director, not the house. They are usually arranged by close family, and specific formats (wreaths, sprays) are ordered through the funeral director or a florist who works with them. If you are not immediate family, you are usually not expected to send these.</p>
\t\t<p><strong>Flowers to the family's home.</strong> This is what most people mean, and what this page covers. A bouquet sent to the house says you are thinking of them. It can be sent any time — before the funeral, or in the weeks after, when the visitors have stopped coming and the house has gone quiet. Flowers in week three are often worth more than flowers in week one.</p>

\t\t<h2>What to send</h2>
\t\t<p>White or soft-coloured flowers are traditional and always appropriate. Lilies, white roses, freesias, or a mixed arrangement in muted colours. Nothing bright, nothing celebratory. A medium size is right. This is not an occasion where larger says more.</p>

\t\t<h2>What to write</h2>
\t\t<p>Short and plain. You cannot fix anything with the card, and you should not try. Do not say "everything happens for a reason." Do not say "at least" anything. These lines are enough:</p>
\t\t<p>"So sorry for your loss. Thinking of you all."</p>
\t\t<p>"With love and deepest sympathy."</p>
\t\t<p>"He was a good man and we will miss him." <em>(Use the person's name if you knew them. Naming them matters.)</em></p>
\t\t<p>"Thinking of you. No need to reply."</p>
\t\t<p>That last line — "no need to reply" — is a kindness. Grieving people face a mountain of thank-you notes. Releasing them from one is a real gift.</p>

\t\t<h2>Timing</h2>
\t\t<p>There is no wrong time. Before the funeral, after it, a month later. If you have only just heard, it is not too late.</p>

