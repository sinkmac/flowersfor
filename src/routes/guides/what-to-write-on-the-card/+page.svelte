		<h1>What to Write on a Flower Card (Copy These)</h1>

\t\t<p class="lede">The flowers are sorted. Now there's a small white card and a pen, and your mind has gone completely empty. This page is the answer. Take any of these word for word — nobody will ever know, and honestly, nobody would mind.</p>

\t\t<h2>The rules first — there are only three</h2>
\t\t<p><strong>1. Short beats long.</strong> A flower card is not a letter. One to three lines. If you've more to say, say it in person; the card's job is to make her want that conversation.</p>
\t\t<p><strong>2. Write it by hand if you can.</strong> If you're ordering online, the printed card is fine — but choose your words like they'll be read twice. They will be.</p>
\t\t<p><strong>3. Sign it the way you actually speak.</strong> If you've never once signed off "with deepest affection" in your life, don't start on a card. She knows how you talk.</p>

\t\t<h2>Apology</h2>
\t\t<p>"I was wrong. I'm sorry. Dinner's on me and so is the washing up — indefinitely."</p>
\t\t<p>"No excuses. I'm sorry, and I'll show it, not just say it."</p>
\t\t<p>"I've replayed it and you were right. Sorry it took me this long."</p>
\t\t<p><em>Avoid:</em> "Sorry you were upset." That's not an apology, that's a deflection with a stamp on it, and it will be noticed.</p>

\t\t<h2>Anniversary</h2>
\t\t<p>"Ten years and you still make me nervous in the best way. Happy anniversary."</p>
\t\t<p>"Still my best decision. Happy anniversary, love."</p>
\t\t<p>"Here's to everything so far and all of it still to come."</p>

\t\t<h2>Just because</h2>
\t\t<p>"Saw these and thought of you. No occasion. No agenda. Well — maybe a small agenda."</p>
\t\t<p>"For no reason except that you're you."</p>
\t\t<p>"Thursday seemed like it needed flowers."</p>
\t\t<p>(For what it's worth: "just because" flowers are the highest-value flowers a man can send. No occasion means no obligation, which means she knows you simply thought of her.)</p>

\t\t<h2>New baby</h2>
\t\t<p>"Welcome to the world, little one. Your mum is a hero. Rest when you can — we've got you."</p>
\t\t<p>"Two of you went in, three of you came out. Incredible work."</p>

\t\t<h2>Sympathy</h2>
\t\t<p>Different rules apply — shorter still, plainer still. Do not attempt warmth through length. See our <a href="/guides/sympathy-flowers-etiquette">sympathy guide</a> for lines written for exactly that.</p>
\t\t<p>"Thinking of you all."</p>
\t\t<p>"With love, and so sorry for your loss."</p>

\t\t<h2>Get well</h2>
\t\t<p>"Heard you're under the weather. These are under instruction to cheer the place up."</p>
\t\t<p>"Rest up. The world can wait."</p>

