		<h1>Forgot the Anniversary? Do This Now</h1>

\t\t<p class="lede">Right. Deep breath. You have two jobs and about ten minutes: get flowers moving, and decide what you're going to say. This page does both. Read fast.</p>

\t\t<h2>Step 1 — Order now, read the rest while it processes</h2>
\t\t<p>Same-day delivery exists and today it is your best friend. Order a proper bouquet — medium-to-large, mixed, her colours if you know them, soft pinks and whites if you don't. Do it before you finish this page. The link at the bottom goes to a florist with same-day slots.</p>

\t\t<h2>Step 2 — Do not pretend you remembered</h2>
\t\t<p>This is the crucial move and most men get it wrong. If the flowers arrive at 4pm and you claim you'd planned it all along, you're now a man who forgot <em>and</em> lied. The recovery position is honesty with style:</p>
\t\t<p>"I forgot the date and I'll be honest about that. What I've never forgotten is why I married you."</p>
\t\t<p>"These flowers are late. My love for you isn't. I'm sorry."</p>
\t\t<p>Owning it converts a failure into a small piece of charm. Denying it converts a failure into a character question.</p>

\t\t<h2>Step 3 — The flowers are the opener, not the fix</h2>
\t\t<p>Book something. Tonight if you can, this week if you can't. A table at the place she likes, tickets to something, a night away. The flowers say "I'm sorry"; the plan says "you matter." You need both. Text her the plan before the flowers arrive if possible — then the delivery lands as chapter two of a recovery already underway, not a lone bandage.</p>

\t\t<h2>Step 4 — Write the date down</h2>
\t\t<p>Phone calendar. Annual repeat. Alert set for one week before <em>and</em> the day. While you're in there, add her birthday, your first date, and Valentine's. This page will always be here, but you don't want to need it twice.</p>

\t\t<h2>If it's a big one — 10th, 25th, a number with a zero in it</h2>
\t\t<p>Flowers plus dinner won't fully carry a milestone. Send the flowers today regardless — then plan a proper late celebration and frame it as such: "We're celebrating this properly, just not on the day I should have organised it for." A milestone celebrated two weeks late with real effort beats one scraped together in panic on the day.</p>

