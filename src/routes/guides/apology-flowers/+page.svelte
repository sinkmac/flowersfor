		<h1>Apology Flowers: What to Send and What Never to Send</h1>

\t\t<p class="lede">You've done something, or she thinks you have, which is the same thing. You're here because you want the flowers to say the right thing without making it worse. Good news: this is fixable. Bad news: it's easy to get wrong, and most men get it wrong the same way.</p>

\t\t<h2>The one rule</h2>
\t\t<p>Apology flowers have one job: to show you thought about it. Not that you spent money — that you <em>thought</em>. A £30 bunch chosen right beats a £70 bunch grabbed in panic every single time.</p>

\t\t<h2>What never to send</h2>
\t\t<p><strong>Red roses.</strong> Read that again. Red roses read as romance, not remorse. Sending them after a row says "I'd like to skip the apology and get to the making up," which is precisely the attitude that got you here. Save them for when things are actually good.</p>
\t\t<p><strong>Anything from a petrol station.</strong> She will know. They always know. The cellophane gives it away and the carnations confirm it.</p>
\t\t<p><strong>Lilies.</strong> Strongly associated with sympathy and funerals in the UK. You're apologising, not mourning the relationship. Yet.</p>
\t\t<p><strong>The biggest, most expensive thing on the site.</strong> Oversized bouquets after an argument read as guilt-scaling — the floral equivalent of shouting "I'M SORRY" louder. If the offence was small, an enormous bouquet makes her wonder what else you've done.</p>

\t\t<h2>What to send</h2>
\t\t<p><strong>For an ordinary row:</strong> something seasonal and mixed, in colours she actually likes (if you don't know, soft pinks and whites are the safe honest middle). Medium size. It says "I was wrong and I've calmed down enough to choose properly."</p>
\t\t<p><strong>For a proper apology — you genuinely dropped the ball:</strong> her favourite flower, if you know it. Knowing it <em>is</em> the apology. If you don't know it, that's a different problem the flowers can't fix, but freesias or ranunculus say "I chose carefully" better than anything generic.</p>
\t\t<p><strong>If it's serious:</strong> flowers alone won't do it, and sending only flowers can read as trying to buy your way out. Send a modest, thoughtful bunch <em>with a handwritten card</em> and do the real apology in person. The flowers open the door; they are not the conversation.</p>

\t\t<h2>Timing</h2>
\t\t<p>Same day or next morning. Apology flowers lose roughly half their value every day you wait. Three days later they stop being an apology and become an admission you needed three days.</p>

\t\t<h2>The card</h2>
\t\t<p>Short. Sincere. No jokes — humour on an apology card is you making yourself comfortable, not her. If you're stuck, our <a href="/guides/what-to-write-on-the-card">card message guide</a> has lines you can use word for word.</p>

