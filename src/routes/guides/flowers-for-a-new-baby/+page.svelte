		<h1>Flowers for a New Baby: What New Parents Actually Want</h1>

		<p class="lede">You want to mark the arrival, and flowers feel right. The instinct is good. The timing and the choice matter more than you think, and most people get both wrong in the same way.</p>

		<h2>Timing: a week after beats day one</h2>
		<p>The hospital visit or the first-day flowers feel thoughtful, but new parents are running on adrenaline and visitors. Day one is chaos. By day four or five, the visitors have stopped, the adrenaline has burned out, and the parents are somewhere between exhausted and overwhelmed. Flowers arriving then — when the house is quieter and they can actually see them — land with more meaning.</p>
		<p>If you're a close friend or family, the hospital flowers are fine. If you're not, the home delivery a week later is the better move. It says you are thinking of them when they actually need thinking of.</p>

		<h2>Avoid heavily scented lilies</h2>
		<p>Lilies are traditional for celebrations, but lilies in a baby's room — or anywhere in a new parent's house, if they are breastfeeding or sleep-deprived — can be overwhelming. The pollen also settles on surfaces, which new parents are suddenly anxious about. Choose scent-light flowers or none at all. Soft tulips, white or pale roses, sweet peas, or ranunculus all say celebration without filling the room with fragrance.</p>

		<h2>Size: smaller than you think</h2>
		<p>New parents have clutter everywhere. A massive bouquet in a house that is already struggling with nappies, bottles, and laundry has nowhere to live. A small-to-medium arrangement in a vase they can actually find space for is better. Small and thoughtful will be kept. Large and in the way might end up in the recycling within three days.</p>

		<h2>Colour: skip the pink and blue clichés</h2>
		<p>If you send pink for a girl and blue for a boy, you are making a statement you did not mean to make. White, cream, pale yellow, or soft mixed colours are safer. If you know the parents' taste or home style, try to match that instead of the baby's sex. The flowers are for the parents' pleasure, not the infant's comfort — the baby does not care about pink.</p>

		<h2>What to write on the card</h2>
		<p>Do not assume intimacy. \"Congratulations on [baby's name]\" is fine. If you knew them before the birth, \"Thinking of you both during this big change\" is better than generic celebration language. If you are not close enough to have used the baby's name in conversation before, you are not close enough to use it on the card. Keep it brief. They are not reading long cards right now.</p>

		<h2>If you are not sure what new parents want</h2>
		<p>This is the moment to ask directly. A text — \"We'd love to send flowers. What would you actually like, if anything?\" — is warmer than a guess. Some new parents want flowers. Some are overwhelmed and would rather have help with the house, food, or a walk with the baby. Asking costs nothing and means they get what helps.</p>

