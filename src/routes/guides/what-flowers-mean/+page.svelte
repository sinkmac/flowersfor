		<h1>What Each Flower Actually Reads As</h1>

		<p class="lede">Every bouquet says something before the card is opened. Not in some Victorian flower-language way — in the practical way that a gift is read by the person receiving it. Here's the translation table, so the flowers say what you mean.</p>

		<h2>Red roses — <em>romance, full stop</em></h2>
		<p>The least ambiguous flower in existence. They say desire and commitment. Right for Valentine's, anniversaries, and grand romantic moments. Wrong for apologies (reads as skipping the apology), wrong for colleagues (obviously), wrong for your mum (please).</p>

		<h2>White roses — <em>purity, respect, remembrance</em></h2>
		<p>Weddings and sympathy. Elegant and serious. As a romantic gesture they read slightly formal — like a handshake where a hug was available.</p>

		<h2>Pink roses — <em>affection without pressure</em></h2>
		<p>The diplomat of roses. Warmth, admiration, fondness — romantic-adjacent without the full declaration. Excellent early in a relationship, when red roses would clear the room.</p>

		<h2>Lilies — <em>solemnity, sympathy, occasion</em></h2>
		<p>Beautiful and serious. In the UK they carry a strong funeral association, so deploy carefully in romantic contexts. Also mildly toxic to cats — if she has a cat, this is the detail that proves you pay attention.</p>

		<h2>Tulips — <em>cheerful, honest, modern</em></h2>
		<p>Spring in a vase. They read as unpretentious and genuine — flowers from someone who wanted to brighten a kitchen rather than make a statement. Superb "just because" flowers.</p>

		<h2>Sunflowers — <em>warmth, friendship, plain joy</em></h2>
		<p>Zero romantic ambiguity, which is their superpower. Right for friends, new homes, get-well, and cheering someone up. They read as sunshine, not seduction.</p>

		<h2>Freesias — <em>thoughtfulness</em></h2>
		<p>Fragrant, slightly unusual, quietly classy. Freesias say "I didn't grab the first thing I saw." Strong apology and just-because material.</p>

		<h2>Peonies — <em>luxury and taste (seasonal flex)</em></h2>
		<p>Late spring to early summer only, and everybody who loves them knows it. In season, they're the most coveted flower going. Sending peonies says you know what's good — the floral equivalent of ordering well at a restaurant.</p>

		<h2>Carnations — <em>budget, unless handled well</em></h2>
		<p>Unfairly maligned, but the association is petrol-station bouquets. Fine as supporting cast in a mixed bunch; risky as the headline act.</p>

		<h2>Mixed seasonal bouquets — <em>safe, warm, always right</em></h2>
		<p>The florist's judgement on your behalf. Never wrong for any occasion short of a milestone. When in doubt, this is the answer — and there's no shame in it.</p>

