		<h1>Condolence Message: What to Write in a Sympathy Card</h1>

		<p class="lede">Someone has died, and you have to write on a small card what you cannot possibly say in words. Good news: you don't need to be eloquent. You need to be honest, plain, and kind. Every line below is copyable — take one word for word. Nobody will know, and nobody would mind.</p>

		<p>The two rules that beat every other consideration: <strong>keep it short</strong>, and <strong>say something true about the person who died if you can</strong>. A card that names a person does more than a card that gets the sentiment right. If you weren't close, don't invent closeness — a plain, kind line is exactly right.</p>

		<h2>Short and plain (when in doubt, use these)</h2>
		<p>These are the safest lines in sympathy. They are hard to get wrong because they don't try to explain anything.</p>
		<p>&ldquo;So sorry for your loss. Thinking of you all.&rdquo;</p>
		<p>&ldquo;I'm so sorry. No need to reply — just know I'm thinking of you.&rdquo;</p>
		<p>&ldquo;With love, and my deepest sympathy.&rdquo;</p>
		<p>&ldquo;Thinking of you and your family at this sad time.&rdquo;</p>
		<p>&ldquo;I don't have the right words. I'm just so sorry.&rdquo;</p>
		<p>That last one is genuinely good. <em>&ldquo;I don't have the right words&rdquo;</em> is a real sentence — it is honest, and honesty reads as care.</p>

		<h2>When you knew the person who died</h2>
		<p>Naming them is the single most powerful thing you can put on a sympathy card. It says this death is specific, not generic — they are missed as a particular person, not as a loss.</p>
		<p>&ldquo;John was a good man and we'll miss him terribly.&rdquo;</p>
		<p>&ldquo;I keep thinking about [name] — they were so kind to me when I needed it.&rdquo;</p>
		<p>&ldquo;I loved [name]'s laugh. I'm so sorry.&rdquo;</p>
		<p>&ldquo;There aren't many people like [name]. I feel lucky to have known them.&rdquo;</p>
		<p>Only add a personal memory if you have one that's real. A specific, true moment &mdash; even a small one &mdash; outweighs any grand statement.</p>

		<h2>Longer condolence messages (for close relationships)</h2>
		<p>For someone you're genuinely close to, a little more is welcome — but still not a letter. Two or three sentences, one true memory, one simple offer. Resist the urge to be poetic.</p>
		<p>&ldquo;I was so sad to hear about [name]. They were such a steady, good presence in all our lives, and I'm going to miss them. I'm here for whatever you need — dinners, errands, or someone to sit quietly with. No hurry, no reply needed to this.&rdquo;</p>
		<p>&ldquo;Your mum was one of the warmest people I've ever known. I keep remembering the time she made everyone laugh at the party. I'm so sorry, and I'm here for you.&rdquo;</p>
		<p>&ldquo;I can't imagine how you're feeling. I'm so sorry. When you're ready, there's a casserole in the fridge and I'll be round with tea. Take all the time you need.&rdquo;</p>

		<h2>By relationship</h2>

		<h3>A colleague's loss</h3>
		<p>Business-flat, but between the lines means care. Keep it short and professional-friendly. Don't pry into details.</p>
		<p>&ldquo;So sorry for your loss. Take whatever time you need — we've got everything here.&rdquo;</p>
		<p>&ldquo;Thinking of you and your family. We're all sorry for your loss and covered while you're away.&rdquo;</p>

		<h3>A friend's parent</h3>
		<p>This is common and people feel it keenly. The friend is losing someone who shaped them — acknowledge the weight even if you didn't know the parent well.</p>
		<p>&ldquo;I'm so sorry about your dad. He was clearly someone special. I'm here for you, whatever you need.&rdquo;</p>
		<p>&ldquo;Losing a parent is enormous. I'm so sorry, and I'm not going anywhere.&rdquo;</p>

		<h3>A pet</h3>
		<p>Losing a pet is a real loss, and a surprising number of people don't send anything because they worry it's silly. It isn't. It is a loss that deserves a card. Name the pet.</p>
		<p>&ldquo;So sorry about Bramble. They were such a character — I'll miss seeing them on our walks.&rdquo;</p>
		<p>&ldquo;I'm so sorry for your loss. It hurts because you loved them, and that's nothing to be embarrassed about.&rdquo;</p>
		<em>If you can't remember the pet's name, just say &ldquo;your dog&rdquo; or &ldquo;your cat&rdquo; — don't guess a name.</em>

		<h2>What NOT to write</h2>
		<p>The worst thing a sympathy card can do is sound like a greeting card. These phrases come from a good place but they carry on, and they'd hurt. Avoid all of them:</p>
		<ul>
			<li><strong>&ldquo;They're in a better place.&rdquo;</strong> You don't know where they are, and it dismisses the pain of the people still here.</li>
			<li><strong>&ldquo;Everything happens for a reason.&rdquo;</strong> No it doesn't, and no one in grief wants a philosophy lecture.</li>
			<li><strong>&ldquo;At least they lived a long life&rdquo;</strong> / <strong>&ldquo;at least they had a good life&rdquo;</strong>. There is no consolation to a loss; &ldquo;at least&rdquo; always lands like a slap.</li>
			<li><strong>&ldquo;They're at peace now.&rdquo;</strong> Comforting to some, unbearably presumptuous for others, especially if the person died young or in an upsetting way.</li>
			<li><strong>&ldquo;Time heals.&rdquo;</strong> Technically true in the long run and useless in the moment. It reads as a dismissal.</li>
			<li><strong>&ldquo;You should move on&rdquo;</strong> or <strong>&ldquo;get over it.&rdquo;</strong> Never. Under no circumstances.</li>
			<li><strong>&ldquo;Cheer up&rdquo;</strong> or <strong>&ldquo;Stay strong.&rdquo;</strong> Sympathy cards are not for cheering anyone up.</li>
			<li><strong>Anything that explains or solves the death,</strong> or presumes religion or an afterlife the family may not share.</li>
		</ul>
		<p>A good test: if a sentence makes <em>you</em> feel more comfortable, it's probably more for you than for them. The card isn't about you.</p>

		<h2>When flowers aren't appropriate</h2>
		<p>Flowers are not the automatic right move. Worth checking before you order:</p>
		<ul>
			<li><strong>The family asked for donations instead.</strong> Honour that. Send a card, make the donation.</li>
			<li><strong>&ldquo;Family flowers only&rdquo; at the funeral.</strong> Don't send to the funeral. You can still send a small arrangement to the house a week or two later, when the cards have stopped.</li>
			<li><strong>Cultural or religious differences.</strong> Some traditions don't use flowers at a funeral, and a few see them as the wrong gesture. If you're not sure, it's fine to check gently with the family before sending.</li>
			<li><strong>Some workplaces don't welcome flowers</strong> for a colleague's bereavement, especially any that arrive during a mourning period or to an open office. In the UK a card or a small plant is usually safer if you don't know.</li>
		</ul>
		<p>If flowers aren't right, or you're unsure, the card still matters — and the card is never wrong.</p>

